"""Pydantic schemas for constrained AI extraction and evidence verification."""
from typing import List, Optional
from pydantic import BaseModel, ConfigDict, Field


class EvidenceSpan(BaseModel):
    model_config = ConfigDict(extra="forbid")

    field: str = Field(..., description="Target claim category: 'exploit', 'mitigation', 'product', 'version', or 'severity'")
    exact_quote: str = Field(..., description="Exact substring quoted directly from the advisory source text")
    start_char: Optional[int] = Field(None, description="Starting character offset in source text if known")
    end_char: Optional[int] = Field(None, description="Ending character offset in source text if known")


class AIEnrichmentResult(BaseModel):
    model_config = ConfigDict(extra="forbid")

    summary: str = Field(..., description="Concise analyst-focused summary in plain language")
    cve_ids: List[str] = Field(default_factory=list, description="Extracted CVE identifiers, e.g. ['CVE-2024-3094']")
    affected_products: List[str] = Field(default_factory=list, description="Extracted software or product names")
    affected_versions: List[str] = Field(default_factory=list, description="Extracted version ranges or specific versions")
    exploit_claim: str = Field(default="unknown", description="'active_exploitation', 'poc_available', 'none_reported', or 'unknown'")
    mitigation_claim: str = Field(default="unknown", description="Actionable mitigation or patch guidance, or 'unknown'")
    evidence_spans: List[EvidenceSpan] = Field(default_factory=list, description="Direct quotations from advisory validating the claims")
    
    # Metadata
    is_fallback: bool = Field(default=False, description="True if generated by deterministic rules rather than LLM")
    provider: str = Field(default="none", description="Provider identifier, e.g. 'gemini', 'mock', 'deterministic-rules'")
    model: str = Field(default="none", description="Model name or rule version")
    status: str = Field(default="success", description="'success', 'fallback', or 'rejected'")
    validation_notes: List[str] = Field(default_factory=list, description="Audit notes on substring checks and sanitization")

